interface SidebarProps {
  config: BootstrapConfig;
  open: boolean;
  onClose: () => void;
}

const PARENT_NAV_KEYS: Record<string, string> = {
  POS: "nav.pos",
  Sales: "nav.sales",
  Inventory: "nav.inventory",
  Accounting: "nav.accounting",
  CRM: "nav.crm",
  "Users & Roles": "nav.users_roles",
  Purchases: "nav.purchases",
};

export default function Sidebar({ config, open, onClose }: SidebarProps) {
  const pathname = usePathname();
  const [expanded, setExpanded] = useState<string | null>(null);
  const user = useAuthStore((s) => s.user);
  const { t, dir } = useI18n();

  const translateLabel = (label: string, route?: string): string => {
    if (!route) {
      const fallback = PARENT_NAV_KEYS[label];
      if (fallback) {
        const translated = t(fallback);
        return translated !== fallback ? translated : label;
      }
      return label;
    }
    const slug = route.replace(/^\//, "").replace(/\//g, ".");
    const key = `nav.${slug}`;
    const translated = t(key);
    return translated !== key ? translated : label;
  };

  const toggleSection = (label: string) => {
    setExpanded((prev) => (prev === label ? null : label));
  };

  const hiddenTransform = dir === "rtl" ? "translate-x-full" : "-translate-x-full";

  return (
    <>
      {open && (
        <div
          className="fixed inset-0 bg-black/50 z-40 lg:hidden"
          onClick={onClose}
        />
      )}
      <aside
        className={`w-64 h-screen bg-card border-e border-border flex flex-col fixed inset-y-0 start-0 z-50 transition-transform duration-300 ease-in-out ${
          open ? "translate-x-0" : hiddenTransform
        } lg:translate-x-0`}
      >
        <div className="h-16 flex items-center gap-2.5 px-4 border-b border-border">
          <StoreLogoUploader size={40} interactive={false} />
          <div className="flex-1 min-w-0">
            <p className="text-sm font-semibold text-foreground leading-tight truncate">
              {config.display_name}
            </p>
            <p className="text-[11px] text-muted truncate">
              {businessTypeLabel(t, config.business_type)}
            </p>
          </div>
          <button
            onClick={onClose}
            className="lg:hidden p-1.5 rounded-lg text-muted hover:bg-accent-dim hover:text-foreground transition-colors"
            title={t("common.close")}
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        <nav className="flex-1 overflow-y-auto py-3 px-3">
          {config.navigation.map((node) => {
            const hasChildren = node.children && node.children.length > 0;
            const isExpanded = expanded === node.label;
            const isActive =
              pathname === node.route ||
              (hasChildren &&
                node.children!.some((c) => pathname === c.route));

            return (
              <div key={node.route || node.label} className="mb-0.5">
                {hasChildren ? (
                  <>
                    <button
                      onClick={() => toggleSection(node.label)}
                      className={`w-full flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm transition-colors ${
                        isActive
                          ? "bg-accent-dim text-gold"
                          : "text-muted hover:bg-accent-dim hover:text-foreground"
                      }`}
                    >
                      <Icon name={node.icon} />
                      <span className="flex-1 text-start">{translateLabel(node.label, node.route)}</span>
                      {node.badge && (
                        <span className="text-[10px] font-bold px-1.5 py-0.5 rounded-full animate-pulse bg-gold text-white">
                          {node.badge}
                        </span>
                      )}
                      <svg
                        className={`w-4 h-4 transition-transform ${
                          isExpanded ? "rotate-180" : ""
                        }`}
                        fill="none"
                        viewBox="0 0 24 24"
                        stroke="currentColor"
                        strokeWidth={2}
                      >
                        <path
                          strokeLinecap="round"
                          strokeLinejoin="round"
                          d="M19.5 8.25l-7.5 7.5-7.5-7.5"
                        />
                      </svg>
                    </button>

                    {isExpanded && (
                      <div className="ms-4 mt-0.5 border-s border-border ps-3">
                        {node.children!.map((child) => (
                          <Link
                            key={child.route}
                            href={child.route}
                            onClick={onClose}
                            className={`flex items-center gap-2.5 px-3 py-2 rounded-lg text-sm transition-colors ${
                              pathname === child.route
                                ? "bg-accent-dim text-gold font-medium"
                                : "text-muted hover:text-foreground hover:bg-accent-dim"
                            }`}
                          >
                            <Icon name={child.icon} className="w-4 h-4" />
                            {translateLabel(child.label, child.route)}
                          </Link>
                        ))}
                      </div>
                    )}
                  </>
                ) : (
                  <Link
                    href={node.route}
                    onClick={onClose}
                    className={`flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm transition-colors ${
                      pathname === node.route
                        ? "bg-accent-dim text-gold font-medium"
                        : "text-muted hover:bg-accent-dim hover:text-foreground"
                    }`}
                  >
                    <Icon name={node.icon} />
                    <span className="flex-1">{translateLabel(node.label, node.route)}</span>
                    {node.badge && (
                      <span className="text-[10px] font-bold px-1.5 py-0.5 rounded-full animate-pulse bg-gold text-white">
                        {node.badge}
                      </span>
                    )}
                  </Link>
                )}
              </div>
            );
          })}
        </nav>

        <div className="p-3 border-t border-border">
          <Link
            href="/profile"
            onClick={onClose}
            className="flex items-center gap-2 px-3 py-2 rounded-lg bg-accent-dim hover:bg-accent-dim/70 transition-colors"
          >
            {user?.avatar ? (
              // eslint-disable-next-line @next/next/no-img-element
              <img
                src={user.avatar}
                alt={user.name || "User"}
                className="w-8 h-8 rounded-full object-cover border border-border"
              />
            ) : (
              <div className="w-8 h-8 rounded-full bg-gradient-to-br from-[#1E4E8C] to-[#D49A37] flex items-center justify-center text-xs font-medium text-white">
                {user?.name?.charAt(0)?.toUpperCase() || "U"}
              </div>
            )}
            <div className="flex-1 min-w-0">
              <p className="text-sm font-medium text-foreground truncate">{user?.name || "User"}</p>
              <p className="text-[11px] text-muted truncate">{roleLabel(t, user?.role)}</p>
            </div>
          </Link>
        </div>
      </aside>
    </>
  );
}
